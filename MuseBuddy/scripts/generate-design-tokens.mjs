import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cssPath = path.join(projectRoot, 'src/global.css');
const outputPath = path.join(projectRoot, 'src/constants/design-palette.generated.ts');
const colorPattern = /--mb-color-([a-z0-9-]+):\s*(#[0-9a-f]{6});/g;

function toCamelCase(value) {
  return value.replace(/-([a-z0-9])/g, (_, character) => character.toUpperCase());
}

function renderPalette(css) {
  const entries = [...css.matchAll(colorPattern)].map((match) => [toCamelCase(match[1]), match[2]]);

  if (entries.length === 0) {
    throw new Error('No --mb-color-* variables were found in src/global.css.');
  }

  const duplicateKeys = entries
    .map(([key]) => key)
    .filter((key, index, keys) => keys.indexOf(key) !== index);

  if (duplicateKeys.length > 0) {
    throw new Error(
      `Duplicate MuseBuddy color variables: ${[...new Set(duplicateKeys)].join(', ')}`,
    );
  }

  const lines = entries.map(([key, value]) => `  ${key}: '${value.toUpperCase()}',`);

  return [
    '// Generated by scripts/generate-design-tokens.mjs. Do not edit directly.',
    '',
    'export const museBuddyPalette = {',
    ...lines,
    '} as const;',
    '',
  ].join('\n');
}

async function findInlineColors(directory) {
  const violations = [];

  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const entryPath = path.join(directory, entry.name);

    if (entry.isDirectory()) {
      violations.push(...(await findInlineColors(entryPath)));
      continue;
    }

    if (
      !/\.(?:css|ts|tsx)$/.test(entry.name) ||
      entryPath === cssPath ||
      entryPath === outputPath
    ) {
      continue;
    }

    const source = await readFile(entryPath, 'utf8');
    const lines = source.split('\n');

    lines.forEach((line, index) => {
      if (/(?:#[0-9a-f]{6}\b|rgba?\(|hsla?\()/i.test(line)) {
        violations.push(`${path.relative(projectRoot, entryPath)}:${index + 1}`);
      }
    });
  }

  return violations;
}

const css = await readFile(cssPath, 'utf8');
const expectedOutput = renderPalette(css);

if (process.argv.includes('--check')) {
  const currentOutput = await readFile(outputPath, 'utf8').catch(() => '');
  const inlineColorViolations = await findInlineColors(path.join(projectRoot, 'src'));

  if (currentOutput !== expectedOutput) {
    console.error('Generated design palette is stale. Run pnpm tokens:generate.');
    process.exitCode = 1;
  }

  if (inlineColorViolations.length > 0) {
    console.error(
      `Inline color literals are not allowed outside src/global.css:\n${inlineColorViolations.join('\n')}`,
    );
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, expectedOutput);
}
